/* Build flat topic index for search and picker */
window.topicIndex = {};
window.allTopics = [];
function buildIndex() {
  for (const [grade, subjects] of Object.entries(CURRICULUM_ALL)) {
    for (const [subjKey, subj] of Object.entries(subjects)) {
      for (const unit of subj.units) {
        for (const topic of unit.topics) {
          const tid = `g${grade}-${subjKey}-u${unit.id.split('-')[0]}-t${topic.id.split('-')[1]}`;
          topic._id = tid;
          topic._grade = grade;
          topic._subject = subjKey;
          topic._unit = unit.id;
          topic._unitTitle = unit.title;
          topic._subjectTitle = subj.title;
          topic._subjectIcon = subj.icon;
          topic._subjectColor = subj.color;
          window.topicIndex[tid] = topic;
          window.allTopics.push(topic);
        }
      }
    }
  }
}
buildIndex();